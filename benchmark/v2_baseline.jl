# Wave A: emit machine-readable v2 baseline (benchmark/out/v2-baseline.toml).
using SDPX
using LinearAlgebra
import MultiFloats

function _small_sdp_problem(::Type{T}) where {T}
    k = 3
    m = k * (k + 1) ÷ 2
    c = zeros(T, m)
    c[1] = -one(T)
    A = zeros(T, m, k, k)
    A[1, 1, 1] = one(T)
    A[2, 2, 2] = one(T)
    A[3, 3, 3] = one(T)
    A[4, 1, 2] = one(T); A[4, 2, 1] = one(T)
    A[5, 1, 3] = one(T); A[5, 3, 1] = one(T)
    A[6, 2, 3] = one(T); A[6, 3, 2] = one(T)
    B = zeros(T, m, 1)
    B[1, 1] = one(T); B[2, 1] = one(T); B[3, 1] = one(T)
    return SDPX.ingest(c, [A], [zeros(T, k, k)], B, T[3]; T=T, sparse=false, verbosity=0)
end

function _baseline(::Type{T}) where {T}
    prob = _small_sdp_problem(T)
    opts = SDPX.SolverOptions{T}(algorithm=:sdp, presolve=false, scaling=:none, verbosity=0, iter_max=200)
    ws = SDPX.Workspace(prob; thread_count=1)
    init = SDPX._kkt_cold_start_initialization(ws, prob, opts)
    init.ok || return (ok=false, reason=string(init.reason))
    x, X, y, Y, mu = init.x, init.X, init.y, init.Y, init.μ
    SDPX.newton_step!(ws, prob, opts, x, X, y, Y, mu; iteration=1)
    alloc = minimum(@allocated(SDPX.newton_step!(ws, prob, opts, x, X, y, Y, mu; iteration=2)) for _ in 1:3)
    return (ok=true, alloc=alloc, factorizations=ws.factorizations)
end

function _run()
    mkpath(joinpath(@__DIR__, "out"))
    io = open(joinpath(@__DIR__, "out", "v2-baseline.toml"), "w")
    println(io, "# SDPX v2 baseline (new main). Generated by benchmark/v2_baseline.jl.")
    println(io, "# machine = ", gethostname())
    println(io, "# julia = ", VERSION)
    println(io, "# date = ", string(Dates.now()))
    for (label, T) in ((:float64, Float64), (:float64x2, MultiFloats.Float64x2), (:float64x4, MultiFloats.Float64x4), (:bigfloat256, BigFloat))
        b = T === BigFloat ? setprecision(BigFloat, 256) do; _baseline(T); end : _baseline(T)
        println(io, "[", label, "]")
        println(io, "ok = ", b.ok)
        b.ok || (println(io, "reason = \"", b.reason, "\""); continue)
        println(io, "per_iteration_julia_alloc_bytes = ", b.alloc)
        println(io, "factorizations = ", b.factorizations)
    end
    close(io)
    println("wrote benchmark/out/v2-baseline.toml")
end

using Dates
_run()