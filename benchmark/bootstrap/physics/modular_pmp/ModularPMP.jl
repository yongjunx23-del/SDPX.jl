module ModularPMP

using SHA
using LinearAlgebra
import SDPX

export ModularPMPSpec, ModularPMPArtifact
export modular_pmp_specs, build_modular_pmp, build_modular_pmp_sdp
export halfline_gram_dimensions, reconstruct_even_coefficients
export reconstruct_odd_coefficients, chi_positive_on_halfline
export validate_artifact, canonical_text, stable_fingerprint

const ARTIFACT_SCHEMA_VERSION = 1
const PRIMARY_ARXIV = "0902.2790"
const PRIMARY_VERSION = "0902.2790v2"
const SOURCE_STATUS = :build_only

"""A fixed-gap polynomial-functional feasibility specification.

The physical functional is represented as
`alpha[F_Delta] = chi(Delta) * p_alpha(Delta-gap)`, with
`chi(Delta)=exp(-2*pi*Delta)>0` on the certified half-line.  `basis[k,j]`
is the coefficient of `x^k` in the polynomial generated by functional
coefficient `alpha[j]`; supplying this table is the formula-to-PMP front end.
The current fixture deliberately uses a rational monomial table and makes no
published-bound claim.
"""
Base.@kwdef struct ModularPMPSpec{R<:Rational}
    id::String
    degree::Int
    gap::R
    basis::Matrix{R}
    normalization::Vector{R}
    source::Symbol = :primary_paper
    source_version::String = PRIMARY_VERSION
    reference_status::Symbol = SOURCE_STATUS
    paper_equivalent::Bool = false
end

struct ModularPMPArtifact{R<:Rational}
    schema_version::Int
    spec::ModularPMPSpec{R}
    gram_dimensions::NamedTuple
    witness_alpha::Vector{R}
    witness_polynomial::Vector{R}
    witness_Q::Matrix{R}
    witness_R::Matrix{R}
    provenance::NamedTuple
    fingerprint::String
end

function halfline_gram_dimensions(degree::Int, matrix_dimension::Int=1)
    degree >= 0 || throw(ArgumentError("degree must be nonnegative"))
    matrix_dimension >= 1 || throw(ArgumentError("matrix dimension must be positive"))
    if iseven(degree)
        d = degree ÷ 2
        return (parity=:even, q=matrix_dimension * (d + 1),
            r=matrix_dimension * d, q_blocks=d + 1, r_blocks=d)
    end
    d = (degree - 1) ÷ 2
    return (parity=:odd, q=matrix_dimension * (d + 1),
        r=matrix_dimension * (d + 1), q_blocks=d + 1, r_blocks=d + 1)
end

"""Return coefficients of `V'Q*V + x V'R*V` for even degree `2d`.

The loops intentionally include both `(i,j)` and `(j,i)`, implementing the
coefficient multiplicities of a symmetric Gram matrix without a hidden factor
of two.
"""
function reconstruct_even_coefficients(Q::AbstractMatrix, R::AbstractMatrix)
    qdim = size(Q, 1)
    size(Q, 2) == qdim || throw(DimensionMismatch("Q must be square"))
    d = qdim - 1
    rdim = size(R, 1)
    size(R, 2) == rdim || throw(DimensionMismatch("R must be square"))
    rdim == d || throw(DimensionMismatch("R has wrong parity dimension"))
    out = zeros(promote_type(eltype(Q), eltype(R)), 2d + 1)
    for i in 0:d, j in 0:d
        out[i + j + 1] += Q[i + 1, j + 1]
    end
    for i in 0:(d - 1), j in 0:(d - 1)
        out[i + j + 2] += R[i + 1, j + 1]
    end
    return out
end

"""Return coefficients of `x V'Q*V + V'R*V` for odd degree `2d+1`."""
function reconstruct_odd_coefficients(Q::AbstractMatrix, R::AbstractMatrix)
    qdim = size(Q, 1)
    size(Q, 2) == qdim || throw(DimensionMismatch("Q must be square"))
    size(R) == size(Q) || throw(DimensionMismatch("Q and R dimensions differ"))
    d = qdim - 1
    out = zeros(promote_type(eltype(Q), eltype(R)), 2d + 2)
    for i in 0:d, j in 0:d
        out[i + j + 2] += Q[i + 1, j + 1]
        out[i + j + 1] += R[i + 1, j + 1]
    end
    return out
end

"""Proof obligation for the factored Boltzmann character.

For `Delta >= gap > 0`, `exp(-2*pi*Delta)` is strictly positive.  The
positivity constraint is therefore exactly the polynomial constraint, not an
exponential-cone approximation.  An ExpCone is relevant only when a decision
variable itself occurs in an exponent.
"""
chi_positive_on_halfline(gap::Real) = isfinite(gap) && gap > zero(gap)

function _validate_spec(spec::ModularPMPSpec)
    spec.source === :primary_paper || throw(ArgumentError("source must be :primary_paper"))
    spec.source_version == PRIMARY_VERSION || throw(ArgumentError("source version is not pinned"))
    spec.reference_status === SOURCE_STATUS || throw(ArgumentError("reference status must be :build_only"))
    !spec.paper_equivalent || throw(ArgumentError("PMP fixture is not paper-equivalent"))
    spec.degree >= 0 || throw(ArgumentError("degree must be nonnegative"))
    chi_positive_on_halfline(spec.gap) || throw(ArgumentError("gap must be positive"))
    size(spec.basis) == (spec.degree + 1, length(spec.normalization)) ||
        throw(DimensionMismatch("basis dimensions do not match degree and functional dimension"))
    return nothing
end

function modular_pmp_specs(::Type{R}=Rational{BigInt}) where {R<:Rational}
    basis = Matrix{R}(I, 5, 5)
    normalization = [one(R), zero(R), zero(R), zero(R), zero(R)]
    return (fixed_gap=ModularPMPSpec{R}(
        id="hellerman09/fixed_gap_pmp_d4",
        degree=4,
        gap=R(1) // 4,
        basis=basis,
        normalization=normalization,
    ),)
end

function _provenance()
    return (
        title="A Universal Inequality for CFT and Quantum Gravity",
        author="Simeon Hellerman",
        arxiv=PRIMARY_ARXIV,
        source_version=PRIMARY_VERSION,
        reference_status=SOURCE_STATUS,
        paper_equivalent=false,
        implemented_equations=(
            "Sec. 2.2 and Eqs. 3.18-3.21: fixed-point modular functional setup",
            "Eq. 3.22: derivative-polynomial functional data interface",
            "Eq. 3.28: vacuum functional normalization data interface",
        ),
        factored_character=(
            "alpha[F_Delta]=exp(-2*pi*Delta)*p_alpha(Delta-gap)",
            "exp(-2*pi*Delta)>0 on Delta>=gap>0, so positivity factors exactly",
        ),
        lifting=(
            "even degree 2d: P=V_d' Q V_d + x V_(d-1)' R V_(d-1)",
            "odd degree 2d+1: P=x V_d' Q V_d + V_d' R V_d",
            "coefficient matching is affine and Q,R are PSD Gram blocks",
        ),
        excluded_claims=(
            "finite fixture is not a continuum Hellerman bound",
            "no published numerical objective or optimal functional is claimed",
            "formula table is an injected front-end contract, not a full eta jet",
        ),
    )
end

function _witness(spec::ModularPMPSpec{R}) where {R}
    iseven(spec.degree) || throw(ArgumentError("fixture witness currently uses even degree"))
    dims = halfline_gram_dimensions(spec.degree)
    Q = Matrix{R}(I, dims.q_blocks, dims.q_blocks)
    G = Matrix{R}(I, dims.r_blocks, dims.r_blocks)
    p = reconstruct_even_coefficients(Q, G)
    alpha = copy(p)
    # The monomial fixture has normalization alpha[1]=1.
    dot(spec.normalization, alpha) == one(R) ||
        throw(ArgumentError("fixture witness violates normalization"))
    return alpha, p, Q, G
end

function build_modular_pmp(spec::ModularPMPSpec{R}) where {R}
    _validate_spec(spec)
    dims = halfline_gram_dimensions(spec.degree)
    alpha, polynomial, Q, G = _witness(spec)
    provisional = ModularPMPArtifact(
        ARTIFACT_SCHEMA_VERSION, spec, dims, alpha, polynomial, Q, G,
        _provenance(), "",
    )
    return ModularPMPArtifact(
        provisional.schema_version, provisional.spec, provisional.gram_dimensions,
        provisional.witness_alpha, provisional.witness_polynomial,
        provisional.witness_Q, provisional.witness_R, provisional.provenance,
        stable_fingerprint(provisional),
    )
end

build_modular_pmp(scale::Symbol, ::Type{R}=Rational{BigInt}) where {R<:Rational} =
    build_modular_pmp(getproperty(modular_pmp_specs(R), scale))

function _gram_coefficient(X, blocks, power)
    terms = Any[]
    for i in 0:(blocks - 1), j in 0:(blocks - 1)
        i + j == power || continue
        # Scalar univariate fixture: both off-diagonal orientations are
        # visited, so symmetric Gram multiplicities are retained.
        push!(terms, X[i + 1, j + 1])
    end
    return isempty(terms) ? 0 : sum(terms)
end

"""Lower the fixed-gap functional to an ordinary affine SDP.

The outer gap search is intentionally not hidden here: callers construct one
artifact per fixed gap and perform a separately recorded bisection. This
function only builds the convex inner feasibility problem.
"""
function build_modular_pmp_sdp(spec::ModularPMPSpec{R}, ::Type{T}=Float64) where
    {R<:Rational,T<:AbstractFloat}
    _validate_spec(spec)
    iseven(spec.degree) || throw(ArgumentError("SDP fixture currently uses even degree"))
    d = spec.degree ÷ 2
    nalpha = size(spec.basis, 2)
    model = SDPX.Model(T; name="modular_fixed_gap_pmp")
    alpha = SDPX.variable!(model, :functional, nalpha; domain=SDPX.Reals())
    Q = SDPX.variable!(model, :gram_even, d + 1, d + 1; domain=SDPX.PSDCone())
    Rgram = d == 0 ? nothing : SDPX.variable!(model, :gram_odd, d, d; domain=SDPX.PSDCone())
    norm_terms = Any[-one(T)]
    for j in 1:nalpha
        coefficient = T(spec.normalization[j])
        iszero(coefficient) || push!(norm_terms, coefficient * alpha[j])
    end
    SDPX.constraint!(model, :functional_normalization, sum(norm_terms), SDPX.ZeroCone())
    for k in 0:spec.degree
        terms = Any[]
        for j in 1:nalpha
            coefficient = T(spec.basis[k + 1, j])
            iszero(coefficient) || push!(terms, coefficient * alpha[j])
        end
        lhs = isempty(terms) ? zero(T) : sum(terms)
        rhs = _gram_coefficient(Q, d + 1, k)
        if d > 0 && k >= 1
            rhs += _gram_coefficient(Rgram, d, k - 1)
        end
        SDPX.constraint!(model, Symbol(:polynomial_coefficient_, k), lhs - rhs, SDPX.ZeroCone())
    end
    SDPX.objective!(model, SDPX.Minimize(), zero(T))
    return SDPX.canonicalize(SDPX.compile_product_cone_model(model))
end

function canonical_text(artifact::ModularPMPArtifact)
    io = IOBuffer()
    println(io, "modular-pmp-schema=", artifact.schema_version)
    for name in fieldnames(typeof(artifact.spec))
        println(io, "spec.", name, '=', repr(getfield(artifact.spec, name)))
    end
    for (name, value) in pairs(artifact.provenance)
        println(io, "provenance.", name, '=', repr(value))
    end
    for (index, value) in pairs(artifact.witness_alpha)
        println(io, "witness.alpha[", index, "]=", value)
    end
    for (index, value) in pairs(artifact.witness_polynomial)
        println(io, "witness.p[", index, "]=", value)
    end
    return String(take!(io))
end

stable_fingerprint(artifact::ModularPMPArtifact) =
    bytes2hex(SHA.sha256(codeunits(canonical_text(artifact))))

function validate_artifact(artifact::ModularPMPArtifact)
    failures = String[]
    try
        _validate_spec(artifact.spec)
    catch
        push!(failures, "spec")
    end
    dims = halfline_gram_dimensions(artifact.spec.degree)
    artifact.gram_dimensions == dims || push!(failures, "gram_dimensions")
    expected = reconstruct_even_coefficients(artifact.witness_Q, artifact.witness_R)
    expected == artifact.witness_polynomial || push!(failures, "witness_reconstruction")
    dot(artifact.spec.normalization, artifact.witness_alpha) == one(eltype(artifact.witness_alpha)) ||
        push!(failures, "witness_normalization")
    artifact.fingerprint == stable_fingerprint(artifact) || push!(failures, "fingerprint")
    return (valid=isempty(failures), failures=failures)
end

end
