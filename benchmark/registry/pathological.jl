"""Registry entries for the JuMP-free analytic pathological slice."""

function _pathological_spec(
    id,
    family::Symbol,
    problem_type::Symbol,
    tiers,
    tags,
    purpose::Symbol,
    loader::Symbol,
    parameters::NamedTuple;
    status::Symbol=:optimal,
    objective=nothing,
    absolute_tolerance::Float64=1.0e-7,
    relative_tolerance::Float64=1.0e-7,
    size=(;),
    seed::Integer=1001,
)
    return BenchmarkSpec(
        id,
        uppercase(last(split(id, '/'))),
        family,
        problem_type,
        :synthetic,
        Tuple(tiers),
        Tuple((:generated, :pathological, tags...)),
        purpose,
        Int(seed),
        loader,
        parameters,
        BenchmarkReference(
            status,
            objective,
            absolute_tolerance,
            relative_tolerance,
            "typed analytic pathological construction; verify in original coordinates",
        ),
        size,
        nothing,
    )
end

