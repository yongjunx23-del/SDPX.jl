function _synthetic(
    id, family, problem_type, tiers, tags, purpose, seed, loader, parameters;
    objective=nothing,
    status=:optimal,
    tolerance=1.0e-7,
    size=(;),
)
    return BenchmarkSpec(
        id,
        replace(id, '/' => ' '),
        family,
        problem_type,
        :synthetic,
        tiers,
        (:synthetic, tags...),
        purpose,
        seed,
        loader,
        parameters,
        BenchmarkReference(
            status,
            objective,
            tolerance,
            tolerance,
            "deterministic analytic construction",
        ),
        size,
        nothing,
    )
end

